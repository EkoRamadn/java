package soalkedua;

public class Ppn {
    private int ppnCen, ppnIdr;

    public int getPpnCen() {
        return ppnCen;
    }

    public void setPpnCen(int ppnCen) {
        this.ppnCen = ppnCen;
    }

    public int getPpnIdr() {
        return ppnIdr;
    }

    public void setPpnIdr(int ppnIdr) {
        this.ppnIdr = ppnIdr;
    }

    public Ppn(int ppnCen, int ppnIdr) {
        this.ppnCen = ppnCen;
        this.ppnIdr = ppnIdr;
    }
}
